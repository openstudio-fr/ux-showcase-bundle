use OpenStudio\UxShowcaseBundle\Library\ComponentStatus;
use Symfony\Component\Config\Definition\Builder\ArrayNodeDefinition;
use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $definition): void {
    $root = $definition->rootNode();
    // A CSS colour that can be written into a style attribute as it is: nothing that closes the attribute or the declaration.
    $isNotAColour = static fn (mixed $color): bool => null !== $color && (!is_string($color) || 1 !== preg_match('/^(#(?:[0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})|[a-z]{3,30}|(?:rgb|hsl)a?\\([0-9a-z.,%\\s\/+-]{1,60}\\))$/iD', $color));
    assert($root instanceof ArrayNodeDefinition);
    $root
        ->children()
            ->scalarNode('title')->defaultValue('Components')->cannotBeEmpty()->end()
            ->scalarNode('logo')->defaultNull()->end()
            ->arrayNode('theme')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('primary_color')
                        ->info('CSS colour of the links, of the active entry of the menu and of the accents of the screens; none by default.')
                        ->defaultNull()
                        ->validate()
                            ->ifTrue($isNotAColour)
                            ->thenInvalid('The primary colour is a hexadecimal colour, a colour name, or an rgb(), rgba(), hsl() or hsla() colour.')
                        ->end()
                    ->end()
                    ->scalarNode('page_background')
                        ->info('CSS colour of the page behind the content of the screens (the header, the menu and the bottom bar stay white); a light grey by default.')
                        ->defaultNull()
                        ->validate()
                            ->ifTrue($isNotAColour)
                            ->thenInvalid('The page background is a hexadecimal colour, a colour name, or an rgb(), rgba(), hsl() or hsla() colour.')
                        ->end()
                    ->end()
                    ->scalarNode('block_background')
                        ->info('CSS colour of the blocks the previews, the try form and the lists of the home page sit in; white by default.')
                        ->defaultNull()
                        ->validate()
                            ->ifTrue($isNotAColour)
                            ->thenInvalid('The block background is a hexadecimal colour, a colour name, or an rgb(), rgba(), hsl() or hsla() colour.')
                        ->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('viewports')
                ->info('Preview widths, in display order: name => width in pixels, or null for a responsive preview.')
                ->performNoDeepMerging()
                ->useAttributeAsKey('name')
                ->normalizeKeys(false)
                ->requiresAtLeastOneElement()
                ->variablePrototype()
                    ->validate()
                        ->ifTrue(static fn (mixed $width): bool => null !== $width && (!is_int($width) || $width < 1))
                        ->thenInvalid('A viewport width is a positive number of pixels, or null for a responsive preview.')
                    ->end()
                ->end()
                ->defaultValue(['responsive' => null, 'mobile' => 375, 'tablet' => 768, 'desktop' => 1280])
            ->end()
            ->arrayNode('backgrounds')
                ->info('Preview backgrounds, in display order: name => a CSS colour, or { color, html_attributes } to also set attributes on the <html> element of the bare page (a theme mode, for instance). An empty list ({}) offers no background.')
                ->performNoDeepMerging()
                ->useAttributeAsKey('name')
                ->normalizeKeys(false)
                ->arrayPrototype()
                    ->beforeNormalization()
                        ->ifString()->then(static fn (string $color): array => ['color' => $color])
                    ->end()
                    ->children()
                        ->scalarNode('color')->isRequired()->cannotBeEmpty()->end()
                        ->arrayNode('html_attributes')
                            ->info('Attributes of the <html> element of the bare page: name => value.')
                            ->useAttributeAsKey('name')
                            ->normalizeKeys(false)
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                    ->end()
                ->end()
                ->defaultValue([
                    'light' => ['color' => '#f8f9fa', 'html_attributes' => []],
                    'white' => ['color' => '#ffffff', 'html_attributes' => []],
                    'dark' => ['color' => '#212529', 'html_attributes' => []],
                ])
            ->end()
            ->scalarNode('fixtures_directory')
                ->info('Directory the JSON fixtures of PHP examples are loaded from, by relative path.')
                ->defaultNull()
            ->end()
            ->arrayNode('preview')
                ->info('Last level of the preview options, below every library.')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('background')->info('A key of backgrounds.')->defaultNull()->end()
                    ->scalarNode('body_class')->defaultNull()->end()
                    ->booleanNode('wrapper')->info('Whether the wrapper of a library surrounds the examples.')->defaultTrue()->end()
                    ->integerNode('height')->min(1)->defaultNull()->end()
                    ->booleanNode('needs_data')->info('Whether the examples read data the check command does not have: it skips them unless --with-data.')->defaultFalse()->end()
                ->end()
            ->end()
            ->arrayNode('libraries')
                ->info('Libraries declared from configuration; a library that needs PHP implements ComponentLibraryInterface instead.')
                ->useAttributeAsKey('name')
                ->normalizeKeys(false)
                ->arrayPrototype()
                    ->children()
                        ->scalarNode('label')->info('Defaults to the name of the library.')->defaultNull()->end()
                        ->scalarNode('prefix')->info('The TwigComponent namespace it covers: "Flexy" covers Flexy:Button and Flexy:Form:Input. Every component when null.')->defaultNull()->end()
                        ->scalarNode('examples')->info('Directory of its Twig example files (*.showcase.twig).')->defaultNull()->end()
                        ->arrayNode('groups')
                            ->info('Display order of the groups.')
                            ->scalarPrototype()->cannotBeEmpty()->end()
                            ->defaultValue([])
                        ->end()
                        ->scalarNode('wrapper')->info('Twig template that surrounds its examples.')->defaultNull()->end()
                        ->scalarNode('bare')->info('Twig template of its bare preview page.')->defaultNull()->end()
                        ->arrayNode('preview')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->scalarNode('background')->defaultNull()->end()
                                ->scalarNode('body_class')->defaultNull()->end()
                                ->booleanNode('wrapper')->defaultNull()->end()
                                ->integerNode('height')->min(1)->defaultNull()->end()
                                ->booleanNode('needs_data')->defaultNull()->end()
                            ->end()
                        ->end()
                        ->arrayNode('needs_data')
                            ->info('Components whose examples read data the check command does not have (the library does not own their example files).')
                            ->scalarPrototype()->cannotBeEmpty()->end()
                            ->defaultValue([])
                        ->end()
                        ->arrayNode('statuses')
                            ->info('Component name => ready, waiting or hidden; the other components are ready.')
                            ->useAttributeAsKey('component')
                            ->normalizeKeys(false)
                            ->enumPrototype()->enumFqcn(ComponentStatus::class)->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('access')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('role')
                        ->info('A Symfony role that opens the showcase outside debug (needs symfony/security-bundle).')
                        ->defaultNull()
                    ->end()
                    ->scalarNode('service')
                        ->info('Id of a ShowcaseAccessInterface service that replaces the default rule entirely.')
                        ->defaultNull()
                    ->end()
                ->end()
            ->end()
        ->end()
    ;
};
